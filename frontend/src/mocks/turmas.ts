export function getFallbackTurmasByDiscipline(
  disciplinaCodigo?: string
): Turma[] {
  const code = (disciplinaCodigo || "").trim().toUpperCase();
  if (code && MOCK_TURMAS_POR_CODIGO[code]) {
    return MOCK_TURMAS_POR_CODIGO[code];
  }
  return MOCK_TURMAS.map((t) => ({
    ...t,
    disciplinaCodigo: code || t.disciplinaCodigo,
  }));
}